"use client";

import { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import Navbar from "@/components/Navbar";
import Footer from "@/components/Footer";
import EmptyState from "@/components/EmptyState";
import UrgencyBadge from "@/components/UrgencyBadge";
import DocumentChecklist from "@/components/DocumentChecklist";
import BirdPathTimeline from "@/components/BirdPathTimeline";
import BirdCheckPanel from "@/components/BirdCheckPanel";
import BirdTrustPanel from "@/components/BirdTrustPanel";
import GeneratedEmailCard from "@/components/GeneratedEmailCard";
import ResourceCard from "@/components/ResourceCard";
import {
  loadResult,
  clearResult,
} from "@/lib/storage";
import {
  isValidDeadline,
  getDeadlineCountdown,
  formatDeadlineDate,
} from "@/lib/validation";
import { getResourceById } from "@/data/resources";
import { downloadICS } from "@/lib/calendar";
import { copyToClipboard } from "@/lib/clipboard";
import { AnalysisResult, CampusResource } from "@/types/analysis";

export default function ResultPage() {
  const router = useRouter();
  const [result, setResult] = useState<AnalysisResult | null>(null);
  const [resource, setResource] = useState<CampusResource | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const data = loadResult();
    if (data) {
      setResult(data);
      if (data.resourceId) {
        const r = getResourceById(data.resourceId);
        if (r) setResource(r);
      }
    }
  }, []);

  if (!result) {
    return (
      <>
        <Navbar />
        <main className="page-content">
          <EmptyState
            title="No analysis result found"
            description="You have not analyzed a message yet. Paste a school email or notice to get your personalized action plan."
            actionLabel="Analyze a Message"
            actionHref="/analyze"
          />
        </main>
        <Footer />
      </>
    );
  }

  const handleCalendarDownload = () => {
    if (result.deadline && isValidDeadline(result.deadline)) {
      const actions = result.actions.slice(0, 3).join("; ");
      downloadICS(
        result.issue,
        result.deadline,
        `Deadline for: ${result.issue}. Actions: ${actions}`
      );
    }
  };

  const handleCopyPlan = async () => {
    const plan = [
      `Bridge Bird Action Plan: ${result.issue}`,
      "",
      `Summary: ${result.summary}`,
      "",
      `Deadline: ${result.deadline ? formatDeadlineDate(result.deadline) : "None detected"}`,
      "",
      "Actions:",
      ...result.actions.map((a, i) => `${i + 1}. ${a}`),
      "",
      `Department: ${result.department}`,
      "",
      "Documents needed:",
      ...result.documents.map((d) => `- ${d}`),
      "",
      `Generated by Bridge Bird on ${new Date().toLocaleDateString()}`,
    ].join("\n");

    const ok = await copyToClipboard(plan);
    if (ok) {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleNewAnalysis = () => {
    clearResult();
    router.push("/analyze");
  };

  return (
    <>
      <Navbar />
      <main className="page-content">
        <div className="result-header">
          <h1 className="result-header__title">Analysis Result</h1>
          <div className="btn-group">
            <button
              className="btn btn--outline"
              onClick={handleNewAnalysis}
            >
              Analyze Another Message
            </button>
            {copied ? (
              <span className="btn btn--primary" aria-live="polite">
                Plan copied!
              </span>
            ) : (
              <button className="btn btn--secondary" onClick={handleCopyPlan}>
                Copy Action Plan
              </button>
            )}
          </div>
        </div>

        {/* Plain-language explanation */}
        <section className="result-section">
          <span className="result-section__label">AI Interpretation</span>
          <h2 className="result-issue">{result.issue}</h2>
          <p className="result-summary">
            <strong>Summary:</strong> {result.summary}
          </p>
          <p className="result-explanation">{result.plainLanguageExplanation}</p>
          <p className="result-explanation" style={{ marginTop: "0.75rem" }}>
            <strong>What could happen if you do not act:</strong>{" "}
            {result.consequence}
          </p>
        </section>

        {/* Urgency + Deadline */}
        <div className="result-grid">
          <section className="result-section">
            <h2 className="result-section__title">Urgency</h2>
            <UrgencyBadge level={result.urgency} />
          </section>

          <section className="result-section">
            <h2 className="result-section__title">Deadline</h2>
            {result.deadline && isValidDeadline(result.deadline) ? (
              <div className="deadline-box">
                <p className="deadline-box__date">
                  {formatDeadlineDate(result.deadline)}
                </p>
                <p
                  className={`deadline-box__countdown ${new Date(result.deadline).getTime() - Date.now() < 7 * 24 * 60 * 60 * 1000 ? "deadline-box__countdown--urgent" : ""}`}
                >
                  {getDeadlineCountdown(result.deadline)}
                </p>
                <button
                  className="btn btn--secondary"
                  onClick={handleCalendarDownload}
                >
                  <svg
                    width="16"
                    height="16"
                    viewBox="0 0 16 16"
                    fill="none"
                    aria-hidden="true"
                  >
                    <rect
                      x="2"
                      y="3"
                      width="12"
                      height="11"
                      rx="1"
                      stroke="currentColor"
                      strokeWidth="1.5"
                    />
                    <path
                      d="M11 2v2M5 2v2M2 6h12"
                      stroke="currentColor"
                      strokeWidth="1.5"
                      strokeLinecap="round"
                    />
                  </svg>
                  Add to Calendar
                </button>
              </div>
            ) : (
              <p className="deadline-box__date">
                No confirmed deadline detected
              </p>
            )}
          </section>
        </div>

        {/* Required documents */}
        <section className="result-section">
          <DocumentChecklist documents={result.documents} />
        </section>

        {/* BirdPath */}
        <section className="result-section">
          <BirdPathTimeline actions={result.actions} />
        </section>

        {/* BirdCheck */}
        <section className="result-section">
          <BirdCheckPanel
            department={result.department}
            departmentReason={result.departmentReason}
            notRecommendedDepartment={result.notRecommendedDepartment}
            notRecommendedReason={result.notRecommendedReason}
          />
        </section>

        {/* BirdTrust */}
        <section className="result-section">
          <BirdTrustPanel
            confidence={result.confidence}
            resourceMatched={!!result.resourceId}
            lastVerified={resource?.lastVerified ?? null}
            needsHumanConfirmation={result.needsHumanConfirmation}
          />
        </section>

        {/* Recommended resource */}
        {resource && (
          <section className="result-section">
            <h2 className="result-section__title">
              <svg
                width="20"
                height="20"
                viewBox="0 0 20 20"
                fill="none"
                aria-hidden="true"
              >
                <path
                  d="M10 18a8 8 0 100-16 8 8 0 000 16z"
                  stroke="var(--color-success)"
                  strokeWidth="2"
                />
                <path
                  d="M7 10l2 2 4-4"
                  stroke="var(--color-success)"
                  strokeWidth="2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
              Recommended campus resource
            </h2>
            <ResourceCard
              resource={resource}
              showWhy={result.departmentReason}
            />
          </section>
        )}

        {/* Email generator */}
        <section className="result-section">
          <GeneratedEmailCard
            subject={result.emailSubject}
            body={result.emailBody}
          />
        </section>

        {/* Actions */}
        <section className="result-section">
          <h2 className="result-section__title">All actions</h2>
          <div className="btn-group">
            <button
              className="btn btn--secondary"
              onClick={handleNewAnalysis}
            >
              Analyze Another Message
            </button>
            {copied ? (
              <span className="btn btn--primary" aria-live="polite">
                Plan copied!
              </span>
            ) : (
              <button className="btn btn--primary" onClick={handleCopyPlan}>
                Copy Action Plan
              </button>
            )}
            {result.deadline && isValidDeadline(result.deadline) && (
              <button
                className="btn btn--outline"
                onClick={handleCalendarDownload}
              >
                Add Deadline to Calendar
              </button>
            )}
            {resource && (
              <a
                href={resource.officialUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="btn btn--outline"
              >
                Open Official Resource
              </a>
            )}
          </div>
        </section>
      </main>
      <Footer />
    </>
  );
}
